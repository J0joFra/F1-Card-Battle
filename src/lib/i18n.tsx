const DICT: Record<Lang, Dict> = { it, en, fr, es, de };

const STORAGE_KEY = 'f1-card-battle:lang';

function initialLang(): Lang {
  try {
    const saved = localStorage.getItem(STORAGE_KEY);
    if (saved && LANGS.some((l) => l.code === saved)) return saved as Lang;
  } catch {
    /* ignora */
  }
  // traduzione automatica: si parte dalla lingua del dispositivo
  const device = (navigator.language || 'it').slice(0, 2).toLowerCase();
  return (LANGS.some((l) => l.code === device) ? device : 'en') as Lang;
}

export type TFn = (key: TKey, params?: Record<string, string | number>) => string;

// Lingua corrente anche fuori da React (formattazione numeri, messaggi dei moduli di gioco).
let currentLang: Lang = initialLang();
export const getLang = () => currentLang;

export const translate: TFn = (key, params) => {
  let s = DICT[currentLang][key] ?? it[key] ?? key;
  if (params) for (const [k, v] of Object.entries(params)) s = s.split(`{${k}}`).join(String(v));
  return s.includes('🪙') ? s.split('🪙').join(coin()) : s; // monete delle feste
};

interface I18nValue {
  lang: Lang;
  setLang: (l: Lang) => void;
  t: TFn;
}

const I18nContext = createContext<I18nValue>({ lang: currentLang, setLang: () => {}, t: translate });

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(currentLang);
  const setLang = useCallback((l: Lang) => {
    currentLang = l;
    setLangState(l);
  }, []);
  useEffect(() => {
    try {
      localStorage.setItem(STORAGE_KEY, lang);
    } catch {
      /* ignora */
    }
    document.documentElement.lang = lang;
  }, [lang]);
  // `t` cambia identità con la lingua, così i componenti che lo usano si aggiornano
  const t = useMemo<TFn>(() => (key, params) => translate(key, params), [lang]); // eslint-disable-line react-hooks/exhaustive-deps
  return <I18nContext.Provider value={{ lang, setLang, t }}>{children}</I18nContext.Provider>;
}

export const useI18n = () => useContext(I18nContext);
